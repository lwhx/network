import { test } from "node:test";
import assert from "node:assert/strict";
import { createServer } from "node:http";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createContainer } from "../src/bootstrap.js";
import { createConfig } from "../src/config/env.js";
import { SpeedTaskStore } from "../src/services/speed-task-store.js";

test("task routes isolate accounts, require CSRF and prevent removal of recovery credentials", async (t) => {
  const dir = mkdtempSync(join(tmpdir(), "speed-task-http-"));
  const container = createContainer(createConfig({ DATA_DIR: dir, SETUP_TOKEN: "token" }));
  container.panelAuthService.createPanelUserSetup({ username: "operator", password: "task-test-password" });
  const first = container.sqliteStore.createCloudflareAccount({ email: "first@example.com", globalApiKey: "first-test-key", name: "First" });
  const second = container.sqliteStore.createCloudflareAccount({ email: "second@example.com", globalApiKey: "second-test-key", name: "Second" });
  const journal = new SpeedTaskStore({ store: container.sqliteStore });
  const zoneId = "a".repeat(32);
  journal.acquireScope(first.id, zoneId);
  const id = journal.begin(first.id, { zoneId, zoneName: "alpha.example", accessDomain: "cdn.alpha.example" });
  journal.save(id, first.id, { steps: [], audit: [] }, { status: "manual_needed" });
  const session = container.credentialSessionService.create({ authenticated: true, activeCloudflareAccountId: first.id });
  const server = createServer(container.app); await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => { server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); container.sqliteStore.close(); rmSync(dir, { recursive: true, force: true }); });
  assert.equal((await fetch(`${origin}/api/speed-tasks`)).status, 401);
  const headers = { cookie: `cf_panel_session=${session.id}`, origin, "Content-Type": "application/json" };
  const listed = await (await fetch(`${origin}/api/speed-tasks`, { headers })).json();
  assert.equal(listed.tasks[0].id, id);
  assert.ok(!JSON.stringify(listed).includes("first-test-key"));
  assert.equal((await fetch(`${origin}/api/speed-tasks/${id}/recover`, { method: "POST", headers, body: '{"confirmation":"yes"}' })).status, 403);
  headers["X-CSRF-Token"] = session.csrfToken;
  assert.equal((await fetch(`${origin}/api/session/cloudflare-accounts/${first.id}`, { method: "DELETE", headers })).status, 409);
  assert.ok(container.cloudflareAccountService.findAccount(first.id));
  container.credentialSessionService.update({ headers: { cookie: headers.cookie } }, { activeCloudflareAccountId: second.id });
  assert.deepEqual((await (await fetch(`${origin}/api/speed-tasks`, { headers })).json()).tasks, []);
  assert.equal((await fetch(`${origin}/api/speed-tasks/${id}`, { headers })).status, 404);
  container.credentialSessionService.update({ headers: { cookie: headers.cookie } }, { activeCloudflareAccountId: first.id });
  assert.equal((await fetch(`${origin}/api/speed-tasks/${id}/recover`, { method: "POST", headers, body: '{}' })).status, 400);
  const recovered = await fetch(`${origin}/api/speed-tasks/${id}/recover`, { method: "POST", headers, body: '{"confirmation":"yes"}' });
  assert.equal(recovered.status, 200);
  assert.equal((await recovered.json()).task.status, "rolled_back");
});
